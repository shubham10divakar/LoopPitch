"""
Render RESULTS.md from results/metrics.csv, paired.csv, loops.csv, convergence_*.json and optimizer summaries.

Usage:
    python make_results.py
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import pandas as pd

from common import RESULTS

OUT = Path("RESULTS.md")


def fmt_ci(r, k):
    return f"{r[k]:.4f} [{r[k + '_lo']:.4f}, {r[k + '_hi']:.4f}]"


def main():
    lines = [f"# Results\n\n_Generated by `make_results.py` on {date.today()}. Test = WC 2022; probabilities "
             "calibrated on out-of-fold predictions; 95% CIs from a match-level bootstrap._\n"]
    deep_cfg = {p.parent.name: json.loads(p.read_text()) for p in (RESULTS / "deep").glob("*/config.json")}

    m = pd.read_csv(RESULTS / "metrics.csv")
    for task, title in [("success", "Pass success (all passes)"), ("shot10", "Shot within 10 s (completed passes)")]:
        d = m[(m.task == task) & (m.probs == "cal")].sort_values("logloss")
        if not len(d):
            continue
        lines += [f"\n## {title}\n", "| Model | Params | Seeds | Log-loss [95% CI] | Brier | BSS | ROC-AUC | PR-AUC | ECE |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for _, r in d.iterrows():
            c = deep_cfg.get(r.model, {})
            lines.append(f"| {r.model} | {c.get('n_params', '') and format(c['n_params'], ',')} | "
                         f"{len(c.get('seeds', [])) or ''} | {fmt_ci(r, 'logloss')} | {r.brier:.4f} | "
                         f"{r.bss:.3f} | {r.auc:.3f} | {r.prauc:.3f} | {r.ece:.4f} |")

    paired = RESULTS / "paired.csv"
    if paired.exists() and paired.stat().st_size > 5:
        pdf = pd.read_csv(paired)
        lines += ["\n## Paired comparisons (calibrated log-loss difference, negative = first model better)\n",
                  "| Task | Model | vs | Δ log-loss | 95% CI | P(better) |", "|---|---|---|---|---|---|"]
        for _, r in pdf.iterrows():
            lines.append(f"| {r.task} | {r.model} | {r.vs} | {r.d_logloss:+.4f} | [{r.lo:+.4f}, {r.hi:+.4f}] | "
                         f"{r.p_better:.2f} |")

    loops = RESULTS / "loops.csv"
    if loops.exists() and loops.stat().st_size > 5:
        lp = pd.read_csv(loops)
        for task in ("success", "shot10"):
            piv = lp[lp.strat == "all"].pivot_table(index="loop", columns="run", values=f"logloss_{task}")
            lines += [f"\n## Per-loop test log-loss, {task} (uncalibrated, seed ensemble; loops beyond the "
                      "trained T are depth extrapolation, H3)\n", piv.round(4).to_markdown()]
        for run in sorted(lp.run.unique()):
            d = lp[(lp.run == run) & (lp.strat == "opp_within_5")]
            if d.loop.nunique() < 2:
                continue
            T = int(d.trained_T.iloc[0])
            g = d[d.loop.isin([1, T])].pivot_table(index="group", columns="loop", values="logloss_success")
            g["gain_1_to_T"] = g[1] - g[T]
            lines += [f"\n### H2 - {run}: success log-loss at loop 1 vs loop {T} by opponents within 5 m\n",
                      g.round(4).to_markdown()]

    for f in sorted(RESULTS.glob("convergence_*.json")):
        c = json.loads(f.read_text())
        lines += [f"\n## State convergence, {c['run']} (trained T = {c['trained_T']})\n",
                  "Mean relative change of the token states, loop t vs t-1, for t = 2, 3, ...: "
                  + ", ".join(f"{v:.3f}" for v in c["rel_change_by_loop"])]

    opt = sorted((RESULTS / "optimizer").glob("*/summary.json"))
    if opt:
        lines += ["\n## Optimizer (EV = P × Q over visible teammates)\n",
                  "| P model | Q model | Split | Passes | Cand./pass | Actual = argmax | Mean Δ | Median Δ | "
                  "Shot rate by EV(actual) quintile |", "|---|---|---|---|---|---|---|---|---|"]
        for f in opt:
            s = json.loads(f.read_text())
            lines.append(f"| {s['p_model']} | {s['q_model']} | {s['split']} | {s['passes']:,} | "
                         f"{s['candidates_per_pass']:.1f} | {s['actual_is_argmax_share']:.1%} | {s['delta_mean']:.4f} | "
                         f"{s['delta_median']:.4f} | {s['shot10_rate_by_EV_actual_quintile']} |")

    lines += ["\n## Figures\n"] + [f"- `{p.as_posix()}`" for p in sorted((RESULTS / "figures").glob("*.png"))]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
